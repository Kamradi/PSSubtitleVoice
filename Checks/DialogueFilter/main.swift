import Foundation
var policy = DialogueTextFilter(enabled:true,requiresSpeaker:true)
for label in ["Залив", "Хэмлет", "Река Пеликан", "Грассриверс", "Вернуться в игру", "Выберите точку назначения.", "Направляйтесь в «Вафли Хэнка».", "Масштаб: 100%"] {
    precondition(!policy.allows(label,at:0),"Not a dialogue: " + label)
}
precondition(!policy.allows("Мы давно не выбирались вот так.",at:0))
precondition(policy.allows("Лусия: Привет.",at:1))
precondition(policy.allows("Я думала, что ты уже ушёл.",at:3))
precondition(policy.allows("Вики: Найдите оружейный магазин.",at:4),"Spoken imperative with a speaker remains dialogue")
precondition(!policy.allows("Залив",at:5),"Map label clears continuation context")
precondition(!policy.allows("Вы успешно установили метку.",at:6))
precondition(policy.allows("[Дэнни] В порядке.",at:7))
precondition(policy.allows("Да.",at:8))
precondition(!policy.allows("Как пройти к магазину?",at:25),"Unnamed text after stale speaker is not a new dialogue")
precondition(policy.allows("New Speaker: Go now!",at:26))
precondition(policy.allows("Go to the car.",at:27))
precondition(DialogueTextFilter.isMenuNavigation("ДЖЕЙСОН И ЛУСИЯ КАРТА ЖУРНАЛ ПРОГРЕСС"))
precondition(DialogueTextFilter.isMenuNavigation("MAP JOURNAL PROGRESS"))
precondition(!DialogueTextFilter.isMenuNavigation("MAP"))
precondition(!DialogueTextFilter.isMenuNavigation("Лусия: Где карта?"))
policy = DialogueTextFilter(enabled:true,requiresSpeaker:false)
precondition(policy.allows("Нам нужно добраться до машины.",at:0))
precondition(!policy.allows("Река Пеликан",at:1))
policy = DialogueTextFilter(enabled:false,requiresSpeaker:true)
precondition(policy.allows("Залив",at:0),"Disabled filter preserves previous behavior")
let gate = SubtitleGate()
gate.configureDialogueOnly(true,requiresSpeaker:true)
precondition(gate.process("Залив",at:0).speech == nil)
precondition(gate.process("Залив",at:0.4).decision.hasPrefix("dialogue_filter_"))
_ = gate.process("Дэнни: В порядке.",at:1)
precondition(gate.process("Дэнни: В порядке.",at:1.4).speech != nil)
_ = gate.process("Я скоро вернусь.",at:2)
precondition(gate.process("Я скоро вернусь.",at:2.4).speech != nil)
gate.reset()
_ = gate.process("Я скоро вернусь.",at:3)
precondition(gate.process("Я скоро вернусь.",at:3.4).speech == nil)
print("PASS: map/menu labels blocked; named speech, continuation, no-name mode, reset and opt-out")
